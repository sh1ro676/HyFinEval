# ---- 裁判委员会：三角色独立视角（多 Agent 第一优先）----
# 核心假设：不同立场的裁判对同一输出会产生真实分歧；分歧度本身可作为
# 「自动评分不确定性」的量化信号——分歧大时标记"需人工复核"，低分歧时
# 自动分可信度高。这是本项目首次在规则评估体系中引入"选择性可信机制"。
